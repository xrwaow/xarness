"""Config autogeneration: ensure_config creates a starter config on first run."""

import json
from pathlib import Path

from xarness.config import DEFAULT_THEME, ensure_config, load_sectioned


def test_missing_config_is_autogenerated(tmp_path: Path) -> None:
    path = tmp_path / "config.json"
    notices = ensure_config(path)
    assert len(notices) == 1 and "created starter config" in notices[0]
    data = json.loads(path.read_text())
    assert data["models"]["openai"]["base_url"] == "https://api.openai.com/v1"
    assert data["models"]["openai"]["model_id"] == "gpt-4.1"
    loaded = load_sectioned(path)
    assert loaded.resolve_model(None)[1].model_id == "gpt-4.1"
    assert loaded.theme == DEFAULT_THEME


def test_existing_config_is_left_alone(tmp_path: Path) -> None:
    path = tmp_path / "config.json"
    path.write_text(json.dumps({
        "models": {"a": {"base_url": "https://api.openai.com/v1", "model_id": "m"}},
    }))
    assert ensure_config(path) == []
    assert "auto_compact_threshold" not in path.read_text()


def test_malformed_existing_config_yields_no_notice(tmp_path: Path) -> None:
    path = tmp_path / "config.json"
    path.write_text("{not json")
    assert ensure_config(path) == []
